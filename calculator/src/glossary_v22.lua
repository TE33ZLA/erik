-- Glossary entries for Weeks 7-12 (merged into the v21 glossary in alphabetical order)
GLOSSARY_NEW = [[## abandonment option
the right to stop a project and sell the
assets if things go badly. Worth
(value with it) - (value without it),
never below zero.
IN QUESTIONS: 'can sell for 60% of cost
after a low year' -> compare sell vs
keep at that date.
-> TYPE 12
## accounting (EBIT) break-even
units that make EBIT = 0:
(fixed costs + Dep) / (P - v).
Ignores tax, interest AND the time
value of money.
IN QUESTIONS: 'accounting break-even',
'EBIT break-even', 'SG&A'.
-> TYPE 11
## after-tax cost of debt
rD x (1 - Tc): interest is tax
deductible, so debt costs less after
tax. rD is the YIELD, not the coupon.
IN QUESTIONS: 'coupon 10%, YTM 4.25%,
tax 30%' -> 4.25% x 0.7.
-> TYPE 20
## alpha
forecast return - CAPM required return.
Positive: above the SML, undervalued
(buy). Negative: overvalued (sell).
-> TYPE 19
## beta
a share's market (systematic) risk:
Cov(R, market) / Var(market). The
market has beta 1. Portfolio beta =
weighted average of the betas.
IN QUESTIONS: 'beta of 1.55', or from
a covariance / correlation.
-> TYPE 19
## CAPM
capital asset pricing model:
required return = rf + beta x
(E[RM] - rf). Only market risk
(beta) earns a reward.
-> TYPE 19
## cash conversion cycle (cash cycle)
days that cash is tied up:
inventory days + A/R days - A/P days.
Shorter is better. Can be negative.
IN QUESTIONS: 'cash cycle', 'CCC'.
-> TYPE 14
## chance node
a point in a decision tree where
chance decides (a circle). Worth the
probability-weighted average of its
branches, then discounted to today.
-> TYPE 12
## coefficient of variation (CV)
SD / expected return: risk for each 1%
of return. A risk-averse investor picks
the LOWEST CV.
-> TYPE 17
## conditional probability
the chance of something GIVEN what
happened before: P(L2 | L1) =
P(L1 and L2) / P(L1).
IN QUESTIONS: 'after a low year, demand
stays low with probability 80%'.
-> TYPE 13
## correlation
how two returns move together, from -1
to +1: Cov / (SD1 x SD2). Below +1
means diversification lowers risk.
-> TYPE 18
## cost of capital
the return investors require for the
risk: the discount rate. For the whole
firm: the WACC.
-> TYPE 20
## cost of equity
the return shareholders require: CAPM
(rf + beta x premium) or dividend
growth (D1/P0 + g).
-> TYPE 20
## cost of preference shares
rP = preference dividend / price. No
tax adjustment (dividends are not tax
deductible).
IN QUESTIONS: 'pays 10% of par $20,
price $22.86'.
-> TYPE 20
## covariance
how two returns move together, in %^2:
sum p(RA - E[RA])(RB - E[RB]) for a
forecast; divide by n - 1 for a sample.
= correlation x SD1 x SD2.
-> TYPE 18
## credit policy
the terms a firm gives its customers
(cash discount, days to pay). Judge a
change with NPV: new - current.
IN QUESTIONS: 'drops the 1% cash
discount', 'customers pay in 30 days'.
-> TYPE 16
## decision node
a point in a tree where MANAGERS choose
(a square). Worth its BEST option, not
an average.
-> TYPE 12
## decision tree
a map of choices (squares) and chances
(circles) over time. Solve it from right
to left: average at chance nodes, pick
the best at decision nodes, discount.
-> TYPE 12
## diversification
holding many shares: company-specific
(unsystematic) risk cancels out, market
(systematic) risk stays.
-> TYPE 18
## expected return
the probability-weighted average return:
sum p x R. With past data: the average.
IN QUESTIONS: 'states of the economy',
'forecast', 'boom / normal / recession'.
-> TYPE 17
## expected value
sum of probability x value. In a tree
it values a chance node.
IN QUESTIONS: '$440,000 with probability
90% or $176,000 ...'.
-> TYPE 12
## holding-period return
the total return over several years:
(1 + R1)(1 + R2)... - 1. Annualise it
with ^(1/n) - 1.
-> TYPE 17
## interest tax shield
the tax saved because interest is tax
deductible: Tc x interest each year.
Permanent debt: PV = Tc x D.
-> TYPE 21
## inventory days
inventory / (COGS/365): how long stock
sits before it is sold.
-> TYPE 14
## joint probability
the chance of a whole path, e.g. low
in year 1 AND low in year 2 =
P(L1) x P(L2 | L1). All paths add to 1.
-> TYPE 13
## leverage (capital structure)
using debt. With more debt the cost of
equity rises (MM Proposition II).
-> TYPE 21
## market risk premium
E[RM] - rf: the extra return the market
pays over the risk-free rate.
-> TYPE 19
## market values (weights)
the WACC uses MARKET values: shares x
share price, bonds x bond price; not
book values.
-> TYPE 20
## Modigliani-Miller (MM)
no tax: capital structure does not
change firm value; rE = rU + D/E
(rU - rD); the WACC stays rU.
With tax: VL = VU + Tc x D and
rE = rU + D/E (rU - rD)(1 - Tc).
-> TYPE 21
## net working capital (NWC)
current assets - current liabilities
(cash, receivables, inventory minus
payables). An increase uses cash.
-> TYPE 14
## NPV break-even
units that make NPV = 0: the yearly
cash flow must repay the outlay like a
loan (I / annuity factor). Includes
the cost of capital.
IN QUESTIONS: 'how many units make the
NPV zero'.
-> TYPE 11
## operating cycle
inventory days + A/R days: from buying
stock to collecting the cash.
-> TYPE 14
## payables days (A/P days)
payables / (COGS/365): how long the
firm takes to pay its suppliers.
-> TYPE 14
## portfolio standard deviation
sqrt(wA^2 sA^2 + wB^2 sB^2 +
2 wA wB Cov): lower than the average
SD unless the correlation is +1.
-> TYPE 18
## real option
a right (not an obligation) to change a
project later: expand, abandon, wait,
upgrade. Adds value: never below 0.
-> TYPE 12
## receivables days (A/R days)
receivables / (sales/365): how long
customers take to pay. Uses SALES.
-> TYPE 14
## risk-free rate
the return on a safe asset (government
bills). Its SD is 0. Inflation up ->
rf up.
-> TYPE 19
## scenario analysis
change SEVERAL inputs together (worst /
base / best case) and find the NPV of
each; then an expected NPV.
-> TYPE 11
## security market line (SML)
the CAPM line: required return against
beta. Above the line: undervalued;
below: overvalued.
-> TYPE 19
## sensitivity analysis
change ONE input, keep the rest at base,
and see how far the NPV moves. The
biggest move = the most sensitive input.
-> TYPE 11
## Sharpe ratio
(E[R] - rf) / SD: extra return per unit
of total risk. Higher is better.
-> TYPE 17
## standard deviation
the spread of returns: square root of
the variance. Forecast: sum p(R -
E[R])^2; sample: divide by n - 1.
-> TYPE 17
## stretching payables
paying suppliers after the due date.
Cheaper credit, but risks the supplier,
cash-on-delivery terms and your rating.
-> TYPE 15
## systematic risk
market risk (interest rates, the
economy): cannot be diversified away.
Measured by beta. The only risk that is
rewarded.
-> TYPE 19
## trade credit
buying now and paying the supplier
later. Terms like 2/10 net 30: 2% off if
paid in 10 days, else due in 30.
Skipping the discount costs
(1 + d/(1 - d))^(365/(N - D)) - 1.
-> TYPE 15
## unlevered cost of capital (rU)
the cost of capital with no debt: the
pre-tax WACC rE(E/V) + rD(D/V).
-> TYPE 21
## unsystematic risk
company-specific risk (a strike, a new
product): diversifies away, so it earns
no extra return.
-> TYPE 18
## collection float
cash customers have already sent that
the firm cannot use yet (in the post,
being processed, clearing at the bank).
Less float = the cash arrives sooner.
IN QUESTIONS: 'a lockbox (or billing
firm) cuts collection time by 2 days
for a fee' -> cash freed today = daily
collections x days; NPV = cash freed
- PV(fees).
-> TYPE 14
## disbursement float
money the firm has paid (a cheque sent)
that has not left its account yet. It
keeps the cash a little longer, so it
works in the firm's favour.
IN QUESTIONS: the opposite of collection
float: the firm is the one paying.
-> TYPE 14
## financial distress costs
the costs of being close to (or in)
bankruptcy: legal fees (direct), lost
customers, suppliers and staff
(indirect). They rise with debt.
Textbook, not on the sheet: VL = VU +
PV(tax shield) - PV(distress costs).
IN QUESTIONS: 'PV of distress costs'
(subtract it), or 'the cash flows fall
because of distress' (use the lower one).
-> TYPE 21
## incremental depreciation
the new asset's depreciation minus the
old asset's (which is lost if you
replace). Only the difference changes
the tax. It turns negative once the new
asset is fully depreciated but the old
one would still be.
-> TYPE 22
## lockbox (billing service)
a bank or firm that collects customer
payments faster for a fee: it cuts the
collection float.
-> TYPE 14
## option to wait (timing option)
the right to delay a decision until you
know more. Waiting lets you go ahead
only when the news is good. Worth
NPV(wait) - NPV(act now) when positive.
IN QUESTIONS: 'book now for $500, or wait
and pay $750 later only if you can go'.
-> TYPE 12
## replacement decision
swap an old asset for a new one? Use
INCREMENTAL cash flows: new minus old,
including the old asset's sale now (after
tax) and its lost depreciation. Replace
if the NPV is above 0.
IN QUESTIONS: 'replace the old machine',
'book value of the old machine', 'cost
savings of $X a year'.
-> TYPE 22
## trade-off theory
the best amount of debt balances the
interest tax shield against the costs of
financial distress. Textbook, not on the
formula sheet.
-> TYPE 21
## unlevered free cash flow
the cash flow the firm's assets make
with no debt: EBIT x (1 - Tc) (+ Dep -
CapEx - change in NWC). Forever:
VU = FCF/rU.
IN QUESTIONS: 'EBIT of $1,000 a year
forever, tax 30%' -> FCF = 700.
-> TYPE 21
## WACC
weighted average cost of capital:
rE(E/V) + rP(P/V) + rD(1 - Tc)(D/V),
market-value weights. The discount rate
for projects as risky as the firm.
-> TYPE 20
## abnormal return
a return above what the risk requires
(e.g. above the CAPM return). An
efficient market rules out abnormal
returns from known information, not
normal returns for bearing risk.
## adverse selection
investors know managers like to sell
shares when they are overpriced. So a
share issue is read as bad news and
the price falls. Like a used-car buyer
who offers less because the seller
knows more.
## agency costs (of debt)
value lost when one group acts for
itself, not for the firm.
Managers vs owners: perks, empire
building. Debt REDUCES these (less
spare cash to waste).
Equity vs lenders near default: risky
gambles, under-investment, cashing
out. Debt CAUSES these.
IN QUESTIONS: agency cost = firm value
under the firm's best plan - firm
value under the plan equity picks.
-> TYPE 21
## asset substitution (excessive risk-taking)
near default, shareholders back a very
risky project, even one with a
negative NPV: they keep the upside,
lenders bear the downside. Firm value
falls.
IN QUESTIONS: 'which plan do the
shareholders prefer?' -> equity gets
max(payoff - debt, 0) in each state.
-> TYPE 21
## asymmetric information
managers know more about the firm's
future than outside investors. So
investors read signals from what the
firm does: borrowing, issuing shares,
paying dividends, buying back shares.
## book value weights
weights from the balance sheet (face
value of debt, book equity). Old
numbers, so NOT used in the WACC: use
market values, which are current.
IN QUESTIONS: 'book value per share',
'face value of the bonds' -> book
weights; 'which is more relevant?' ->
market weights.
-> TYPE 20
## capital gains tax (CGT) discount
Australian individuals who hold shares
for more than 12 months pay tax on
only 50% of the gain. Held for less:
the whole gain is taxed.
IN QUESTIONS: 'held for two years' ->
halve the gain, then apply the tax
rate.
-> TYPE 23
## cashing out
near default, paying as much cash as
possible to shareholders (e.g. a big
dividend) before the lenders take
over. An agency cost of debt.
-> TYPE 21
## classical tax system
company profit is taxed, then the
dividend is taxed again in the
shareholder's hands: double taxation
(e.g. the US). It makes buy-backs more
attractive than dividends.
-> TYPE 23
## cum-dividend
'with the dividend': a share bought
before the ex-dividend date comes with
the right to the next dividend.
-> TYPE 23
## debt overhang (under-investment)
near default, shareholders refuse to
fund a positive-NPV project, because
most of the gain would go to the
lenders. The lost NPV is an agency
cost.
IN QUESTIONS: 'would the shareholders
put up the money?' -> compare what
they pay in with what equity gains.
-> TYPE 21
## declaration date
the day the board announces a
dividend: its amount and its dates.
Order: declaration, ex-dividend,
record, payment.
## direct costs of financial distress
fees to run a bankruptcy: lawyers,
accountants, administrators. Only a
few % of firm value on average.
Legal and accounting fees are DIRECT,
not indirect.
-> TYPE 21
## dividend irrelevance (MM)
in a perfect market, with investment
policy fixed, payout policy does not
change the share price. Dividends or
buy-backs, now or later: same value.
-> TYPE 23
## dividend signalling
dividend changes carry managers' news.
A raise: they expect to afford it
(good news). A cut: often trouble, but
it can mean the cash is going into
new positive-NPV projects.
## dividend smoothing
keeping dividends steady: raise them
only when higher earnings look
lasting; cut them only as a last
resort.
## divisional cost of capital
a separate rate for each division, set
by that division's risk. A project
must beat its own division's rate, not
the firm's WACC.
IN QUESTIONS: 'divisions', 'IRR vs
the divisional cost of capital'.
-> TYPE 20
## effective annual cost of debt
the lectures' yearly pre-tax cost of
debt for a semi-annual bond:
(1 + y)^2 - 1, with y the yield per
half-year. Pearson / textbook answers
often use the APR y x 2 instead.
IN QUESTIONS: semi-annual coupons +
'cost of debt' -> find y from the
price, then (1 + y)^2 - 1, then
x (1 - Tc) for the after-tax cost.
-> TYPE 20
## efficient market hypothesis (EMH)
prices reflect the information
available, so securities are fairly
priced. No abnormal returns from
information already known. It comes
from keen competition among investors.
## ex-dividend date
the first day the share trades WITHOUT
the dividend. Buy on or after it: no
dividend (the seller keeps it). In a
perfect market the price falls by the
dividend that day.
IN QUESTIONS: 'cum-dividend price 30,
dividend 1.20' -> ex price 28.80.
-> TYPE 23
## flotation costs (issue costs)
fees paid to issue new shares or
bonds (underwriters, lawyers). A real
cash cost of the project: subtract
them from its NPV.
IN QUESTIONS: 'issuance costs paid
when the deal closes' -> NPV =
PV(FCF at the WACC) - price - costs.
-> TYPE 20
## franked dividend
a dividend paid from profit that has
already borne Australian company tax.
It carries franking credits. Fully
franked: credits for all the company
tax on that profit.
-> TYPE 23
## homemade dividend
an investor sells some shares to get
more cash than the dividend gives, or
reinvests a dividend they do not want.
So, in a perfect market, the firm's
dividend choice does not matter.
-> TYPE 23
## homemade leverage
investors borrow or lend on their own
to copy or undo a firm's leverage. In
a perfect market it is a perfect
substitute, so leverage cannot add
value (MM, no tax).
-> TYPE 21
## imputation credit (franking credit)
a credit for company tax already paid,
attached to a franked dividend. The
shareholder adds it to income (gross
up), works out tax at their own rate,
then subtracts the credit.
Credit = dividend x Tc / (1 - Tc).
IN QUESTIONS: 'fully franked dividend
of 14, company tax 30%' -> credit 6,
taxable income 20.
-> TYPE 23
## indirect costs of financial distress
business lost because the firm looks
shaky: lost customers and suppliers,
costs to employees, fire sales of
assets. Often much bigger than the
direct costs. They can start before
default.
-> TYPE 21
## managerial entrenchment
managers who face little threat of
being fired can run the firm for
themselves (perks, low effort, empire
building). Debt helps discipline them.
## market portfolio
every risky asset, held in proportion
to its market value: weight = market
cap / total market cap. In practice a
broad index stands in for it (S&P 500
in the US, S&P/ASX 200 here).
IN QUESTIONS: 'the whole market is
these shares' -> each one's cap / the
total cap.
-> TYPE 19
## market timing
issuing shares when managers think
they are OVERvalued; using debt or
retained earnings when they think the
shares are undervalued.
## overreaction
a biased price response: the first
move is too big and later REVERSES.
## payment date
the day the dividend is paid to the
holders on the register at the record
date (often weeks later).
## payout policy
how a firm returns cash to its
shareholders: how much, how often, and
how (dividends or buy-backs).
-> TYPE 23
## pecking order
fund projects with retained earnings
first, then debt, and new equity only
as a last resort. It comes from
asymmetric information. Unlike the
trade-off theory, it has NO optimal
debt ratio.
## pre-tax cost of debt
the yield (YTM) lenders require on the
firm's bonds today: NOT the coupon
rate. It is before the tax saving on
interest. After tax: rD x (1 - Tc).
-> TYPE 20
## pure play
a firm that does only one kind of
business. Its cost of capital (its rE
from CAPM, if it has no debt) is the
rate for a project in that business.
IN QUESTIONS: 'a new line of business',
'a comparable firm with no debt'.
-> TYPE 20
## record date
the date the firm checks its share
register: holders listed then get the
dividend. To be listed in time, buy
before the ex-dividend date.
## semi-strong-form efficiency
all PUBLIC information (reports, news,
past prices) is in the price.
Analysing public news cannot earn
abnormal returns. Implies the weak
form.
## share repurchase (buy-back)
the firm uses cash to buy back its own
shares: on-market (on the exchange) or
off-market (an offer to shareholders).
Perfect market: the share price stays
the same, and wealth is the same as
with a dividend.
IN QUESTIONS: 'buys back 10% of its
shares at the market price' -> fewer
shares, same price.
-> TYPE 23
## signalling theory of debt
using more debt to signal good
prospects. Weak firms could not afford
the fixed payments, so investors
believe it: more debt -> good news.
## strong-form efficiency
ALL information, public and private,
is in the price. Not even insiders can
earn abnormal returns. Implies the
semi-strong and weak forms.
## subjective approach
put projects into risk classes and add
or subtract an adjustment to the WACC
(e.g. + 4% for risky projects). Rough
but simple.
IN QUESTIONS: 'adjustment factor of
+3%' -> discount at WACC + 3%.
-> TYPE 20
## tax clientele
investors who prefer a payout policy
because of their tax position, e.g.
low-tax super funds like fully franked
dividends. Firms attract the clientele
their policy suits.
## underreaction
a biased price response: the first
move is too small and later CONTINUES
(a delayed reaction).
## weak-form efficiency
past prices and trading volume are
already in today's price. Technical
analysis (chart patterns) cannot earn
abnormal returns.]]
