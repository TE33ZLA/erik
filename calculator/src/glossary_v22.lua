-- Glossary entries for Weeks 7-11 (merged into the v21 glossary in alphabetical order)
GLOSSARY_NEW = [[## abandonment option
the right to stop a project and sell the
assets if things go badly. Worth
(value with it) - (value without it),
never below zero.
IN QUESTIONS: 'can sell for 60% of cost
after a low year' -> compare sell vs
keep at that date.
-> TYPE 12
## accounting (EBIT) break-even
units that make EBIT = 0:
(fixed costs + Dep) / (P - v).
Ignores tax, interest AND the time
value of money.
IN QUESTIONS: 'accounting break-even',
'EBIT break-even', 'SG&A'.
-> TYPE 11
## after-tax cost of debt
rD x (1 - Tc): interest is tax
deductible, so debt costs less after
tax. rD is the YIELD, not the coupon.
IN QUESTIONS: 'coupon 10%, YTM 4.25%,
tax 30%' -> 4.25% x 0.7.
-> TYPE 20
## alpha
forecast return - CAPM required return.
Positive: above the SML, undervalued
(buy). Negative: overvalued (sell).
-> TYPE 19
## beta
a share's market (systematic) risk:
Cov(R, market) / Var(market). The
market has beta 1. Portfolio beta =
weighted average of the betas.
IN QUESTIONS: 'beta of 1.55', or from
a covariance / correlation.
-> TYPE 19
## CAPM
capital asset pricing model:
required return = rf + beta x
(E[RM] - rf). Only market risk
(beta) earns a reward.
-> TYPE 19
## cash conversion cycle (cash cycle)
days that cash is tied up:
inventory days + A/R days - A/P days.
Shorter is better. Can be negative.
IN QUESTIONS: 'cash cycle', 'CCC'.
-> TYPE 14
## chance node
a point in a decision tree where
chance decides (a circle). Worth the
probability-weighted average of its
branches, then discounted to today.
-> TYPE 12
## coefficient of variation (CV)
SD / expected return: risk for each 1%
of return. A risk-averse investor picks
the LOWEST CV.
-> TYPE 17
## conditional probability
the chance of something GIVEN what
happened before: P(L2 | L1) =
P(L1 and L2) / P(L1).
IN QUESTIONS: 'after a low year, demand
stays low with probability 80%'.
-> TYPE 13
## correlation
how two returns move together, from -1
to +1: Cov / (SD1 x SD2). Below +1
means diversification lowers risk.
-> TYPE 18
## cost of capital
the return investors require for the
risk: the discount rate. For the whole
firm: the WACC.
-> TYPE 20
## cost of equity
the return shareholders require: CAPM
(rf + beta x premium) or dividend
growth (D1/P0 + g).
-> TYPE 20
## cost of preference shares
rP = preference dividend / price. No
tax adjustment (dividends are not tax
deductible).
IN QUESTIONS: 'pays 10% of par $20,
price $22.86'.
-> TYPE 20
## covariance
how two returns move together, in %^2:
sum p(RA - E[RA])(RB - E[RB]) for a
forecast; divide by n - 1 for a sample.
= correlation x SD1 x SD2.
-> TYPE 18
## credit policy
the terms a firm gives its customers
(cash discount, days to pay). Judge a
change with NPV: new - current.
IN QUESTIONS: 'drops the 1% cash
discount', 'customers pay in 30 days'.
-> TYPE 16
## decision node
a point in a tree where MANAGERS choose
(a square). Worth its BEST option, not
an average.
-> TYPE 12
## decision tree
a map of choices (squares) and chances
(circles) over time. Solve it from right
to left: average at chance nodes, pick
the best at decision nodes, discount.
-> TYPE 12
## diversification
holding many shares: company-specific
(unsystematic) risk cancels out, market
(systematic) risk stays.
-> TYPE 18
## expected return
the probability-weighted average return:
sum p x R. With past data: the average.
IN QUESTIONS: 'states of the economy',
'forecast', 'boom / normal / recession'.
-> TYPE 17
## expected value
sum of probability x value. In a tree
it values a chance node.
IN QUESTIONS: '$440,000 with probability
90% or $176,000 ...'.
-> TYPE 12
## holding-period return
the total return over several years:
(1 + R1)(1 + R2)... - 1. Annualise it
with ^(1/n) - 1.
-> TYPE 17
## interest tax shield
the tax saved because interest is tax
deductible: Tc x interest each year.
Permanent debt: PV = Tc x D.
-> TYPE 21
## inventory days
inventory / (COGS/365): how long stock
sits before it is sold.
-> TYPE 14
## joint probability
the chance of a whole path, e.g. low
in year 1 AND low in year 2 =
P(L1) x P(L2 | L1). All paths add to 1.
-> TYPE 13
## leverage (capital structure)
using debt. With more debt the cost of
equity rises (MM Proposition II).
-> TYPE 21
## market risk premium
E[RM] - rf: the extra return the market
pays over the risk-free rate.
-> TYPE 19
## market values (weights)
the WACC uses MARKET values: shares x
share price, bonds x bond price; not
book values.
-> TYPE 20
## Modigliani-Miller (MM)
no tax: capital structure does not
change firm value; rE = rU + D/E
(rU - rD); the WACC stays rU.
With tax: VL = VU + Tc x D and
rE = rU + D/E (rU - rD)(1 - Tc).
-> TYPE 21
## net working capital (NWC)
current assets - current liabilities
(cash, receivables, inventory minus
payables). An increase uses cash.
-> TYPE 14
## NPV break-even
units that make NPV = 0: the yearly
cash flow must repay the outlay like a
loan (I / annuity factor). Includes
the cost of capital.
IN QUESTIONS: 'how many units make the
NPV zero'.
-> TYPE 11
## operating cycle
inventory days + A/R days: from buying
stock to collecting the cash.
-> TYPE 14
## payables days (A/P days)
payables / (COGS/365): how long the
firm takes to pay its suppliers.
-> TYPE 14
## portfolio standard deviation
sqrt(wA^2 sA^2 + wB^2 sB^2 +
2 wA wB Cov): lower than the average
SD unless the correlation is +1.
-> TYPE 18
## real option
a right (not an obligation) to change a
project later: expand, abandon, wait,
upgrade. Adds value: never below 0.
-> TYPE 12
## receivables days (A/R days)
receivables / (sales/365): how long
customers take to pay. Uses SALES.
-> TYPE 14
## risk-free rate
the return on a safe asset (government
bills). Its SD is 0. Inflation up ->
rf up.
-> TYPE 19
## scenario analysis
change SEVERAL inputs together (worst /
base / best case) and find the NPV of
each; then an expected NPV.
-> TYPE 11
## security market line (SML)
the CAPM line: required return against
beta. Above the line: undervalued;
below: overvalued.
-> TYPE 19
## sensitivity analysis
change ONE input, keep the rest at base,
and see how far the NPV moves. The
biggest move = the most sensitive input.
-> TYPE 11
## Sharpe ratio
(E[R] - rf) / SD: extra return per unit
of total risk. Higher is better.
-> TYPE 17
## standard deviation
the spread of returns: square root of
the variance. Forecast: sum p(R -
E[R])^2; sample: divide by n - 1.
-> TYPE 17
## stretching payables
paying suppliers after the due date.
Cheaper credit, but risks the supplier,
cash-on-delivery terms and your rating.
-> TYPE 15
## systematic risk
market risk (interest rates, the
economy): cannot be diversified away.
Measured by beta. The only risk that is
rewarded.
-> TYPE 19
## trade credit
buying now and paying the supplier
later. Terms like 2/10 net 30: 2% off if
paid in 10 days, else due in 30.
Skipping the discount costs
(1 + d/(1 - d))^(365/(N - D)) - 1.
-> TYPE 15
## unlevered cost of capital (rU)
the cost of capital with no debt: the
pre-tax WACC rE(E/V) + rD(D/V).
-> TYPE 21
## unsystematic risk
company-specific risk (a strike, a new
product): diversifies away, so it earns
no extra return.
-> TYPE 18
## WACC
weighted average cost of capital:
rE(E/V) + rP(P/V) + rD(1 - Tc)(D/V),
market-value weights. The discount rate
for projects as risky as the firm.
-> TYPE 20]]
